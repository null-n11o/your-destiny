export function annualCopyFor(outlook: Outlook): AnnualCopy {
  const copy = THEMES[outlook.star];
  if (!outlook.isTenchusatsu) return { theme: copy.theme, paragraphs: copy.paragraphs, actions: copy.actions, caution: copy.caution };
  return {
    theme: copy.theme,
    paragraphs: [...copy.paragraphs, "この年の支は、あなたの天中殺の二支に当たる。ここでは、結果を急ぐより、今年のテーマについて棚卸しや練習をする機会として読む。今ある約束を確かめ、休む余白を持ちながら、小さく試せることから選んでいきたい。"],
    actions: copy.quietActions,
    caution: "天中殺という言葉だけで大切な選択を決めない。具体的な条件や本人の希望を確認し、急がず相談できる時間を確保する。",
  };
}
